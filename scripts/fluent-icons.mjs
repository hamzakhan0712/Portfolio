/* Brand marks (Devicon, 128 px grid), recoloured to currentColor. */
const BRANDS = { Github: "github/github-original", Linkedin: "linkedin/linkedin-plain" };

const [fluentPkg, devPkg] = process.argv.slice(2);
if (!fluentPkg || !devPkg) {
  console.error("Pass the extracted @fluentui/svg-icons and devicon package folders.");
  process.exit(1);
}

const inner = (svg) => svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/<title>.*?<\/title>/, "");

const lines = [];
for (const [name, file] of Object.entries(FLUENT)) {
  const svg = fs.readFileSync(path.join(fluentPkg, "icons", `${file}.svg`), "utf8");
  lines.push(`export const ${name} = icon(20, ${JSON.stringify(inner(svg))});`);
}
for (const [name, file] of Object.entries(BRANDS)) {
  const svg = fs.readFileSync(path.join(devPkg, "icons", `${file}.svg`), "utf8");
  const mono = inner(svg).replace(/\sfill="#[0-9a-fA-F]{3,8}"/g, "");
  lines.push(`export const ${name} = icon(128, ${JSON.stringify(mono)});`);
}

const out = `/* Generated by scripts/fluent-icons.mjs — do not edit by hand. */
import type { SVGProps } from "react";

/**
 * Icons from Fluent UI System Icons (MIT), the set Windows 11 uses, drawn in
 * currentColor. Size them with classes (h-4 w-4); they default to 1em.
 * \`strokeWidth\` is accepted and ignored: Fluent glyphs are filled outlines
 * with their weight built in.
 */
export type IconProps = SVGProps<SVGSVGElement> & { strokeWidth?: number | string };
export type Icon = (props: IconProps) => JSX.Element;

function icon(grid: number, markup: string): Icon {
  return function FluentIcon({ strokeWidth: _ignored, ...props }: IconProps) {
    return (
      <svg
        viewBox={\`0 0 \${grid} \${grid}\`}
        width="1em"
        height="1em"
        fill="currentColor"
        aria-hidden
        focusable="false"
        {...props}
        dangerouslySetInnerHTML={{ __html: markup }}
      />
    );
  };
}

/** Windows' indeterminate progress ring, for "working…" states. */
export function ProgressRing({ className, ...props }: SVGProps<SVGSVGElement>) {
  return (
    <svg viewBox="0 0 16 16" width="1em" height="1em" aria-hidden className={className} {...props}>
      <circle
        cx="8"
        cy="8"
        r="6.5"
        fill="none"
        stroke="currentColor"
        strokeWidth="1.5"
        strokeLinecap="round"
        strokeDasharray="10 31"
        className="origin-center animate-spin"
      />
    </svg>
  );
}

${lines.join("\n")}
`;

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
fs.writeFileSync(path.join(root, "src", "components", "icons.tsx"), out);
console.log(`wrote ${Object.keys(FLUENT).length + Object.keys(BRANDS).length} icons`);
